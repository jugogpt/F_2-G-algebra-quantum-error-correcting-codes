"""
Core algebra for k-variate bicycle (kB) codes, following the draft
"The Module Structure of k-variate Bicycle Codes and their Transversal
Symmetries" (AD, HS, JB, IC).

Design choice (documented in the planning discussion): rather than building
the g^(i)_j / L^(i)_j / J_j intermediate scaffolding of Sec 2.2.1 by
factoring x^{l_i'}-1 into irreducibles, we build ONE splitting field
GF(2^N) large enough to contain every l_i'-th root of unity, take the
Cartesian product of the root groups to get all root tuples P, and read
off the component set C directly as the orbits of the diagonal Frobenius
(eq. 12) on P. Component degree D_c falls out as the orbit size. This is
equivalent to Theorem 2.4 by construction but avoids re-deriving the
abstract multi-index bookkeeping the draft itself flags as unclear
("[AJ: need to note why j,d columns in example are same...]").

All local-ring (J_c) arithmetic is then carried out inside the ambient
GF(2^N), since kappa_c = GF(2^{D_c}) is canonically a subfield of GF(2^N)
(D_c | N by construction of N as an lcm).
"""

from __future__ import annotations
from dataclasses import dataclass, field
from itertools import product as iproduct
from functools import reduce
from math import gcd
import galois


# ---------------------------------------------------------------------------
# Ring setup: L = (l_1,...,l_k)  ->  s_i, l_i', e, S, exponent lattice A
# ---------------------------------------------------------------------------

def _val2(n: int) -> int:
    """2-adic valuation: largest s with 2^s | n."""
    s = 0
    while n % 2 == 0:
        n //= 2
        s += 1
    return s


def multiplicative_order(a: int, n: int) -> int:
    """Smallest positive t with a^t == 1 (mod n). Requires gcd(a,n)=1 (n odd here)."""
    if n == 1:
        return 1
    t, x = 1, a % n
    while x != 1:
        x = (x * a) % n
        t += 1
    return t


@dataclass
class RingData:
    L: tuple            # (l_1, ..., l_k)
    k: int
    s: tuple             # s_i = 2-adic valuation of l_i
    lprime: tuple         # l_i' = l_i / 2^{s_i}, odd part
    E: tuple             # indices i with s_i > 0 (even variables), 0-indexed
    e: int               # |E|
    S: int               # sum of s_i
    A: list              # exponent lattice: list of tuples, one coord per i in E,
                          # coordinate range 0..2^{s_i}-1 (the monomial basis of the
                          # nilpotent part of every J_c, Sec 5.5)
    N: int               # degree of the splitting field GF(2^N) holding every l_i'-th root of unity
    GF: object            # galois.GF(2**N) field class
    components: list      # list of Component

    def DL(self) -> int:
        r = 1
        for li in self.L:
            r *= li
        return r


@dataclass
class Component:
    """One CRT component J_c of R_L, i.e. one orbit c of the diagonal Frobenius
    on root tuples (Theorem 2.4)."""
    index: int
    rep: tuple            # a representative root tuple (alpha_1,...,alpha_k), GF(2^N) elements
    orbit: tuple           # full orbit, tuple of root tuples
    Dc: int               # = len(orbit) = [kappa_c : F2]
    dim: int               # dim_F2 J_c = Dc * 2^S


def ring_setup(L: tuple) -> RingData:
    """Build the static ring data for R_L (everything that depends only on
    L = (l_1,...,l_k), not on any particular component)."""
    k = len(L)
    s = tuple(_val2(li) for li in L)
    lprime = tuple(L[i] // (2 ** s[i]) for i in range(k))
    E = tuple(i for i in range(k) if s[i] > 0)
    e = len(E)
    S = sum(s)
    A = [tuple(a) for a in iproduct(*[range(2 ** s[i]) for i in E])] if E else [()]

    # N = lcm of multiplicative orders of 2 mod each (odd) l_i', so that every
    # l_i'-th root of unity lives in GF(2^N) (see planning note / Example 1 check).
    orders = [multiplicative_order(2, lp) if lp > 1 else 1 for lp in lprime]
    N = reduce(lambda a, b: a * b // gcd(a, b), orders, 1)

    GF = galois.GF(2 ** N)
    components = _find_components(L, lprime, S, GF, N)

    return RingData(L=L, k=k, s=s, lprime=lprime, E=E, e=e, S=S, A=A,
                     N=N, GF=GF, components=components)


def _find_components(L, lprime, S, GF, N) -> list:
    """Root-tuple orbits of the diagonal Frobenius phi(a)=(a_1^2,...,a_k^2)
    (eq. 12), giving the component set C of Theorem 2.4.

    Root tuples are represented as tuples of plain Python ints (the integer
    encoding galois uses for GF(2^N) elements) so they can live in sets/dicts;
    GF(...) converts an int back to a field element whenever arithmetic is
    needed, and int(x) converts a field element back down.
    """
    order = GF.order - 1  # |GF(2^N)^*|
    g = GF.primitive_element

    # mu_{l_i'}: the group of l_i'-th roots of unity inside GF(2^N)^*,
    # generated by g^{(2^N-1)/l_i'}. Stored as ints.
    root_groups = []
    for lp in lprime:
        assert order % lp == 0, f"l_i'={lp} does not divide 2^N-1={order}"
        gen = g ** (order // lp)
        pts = [int(GF(1))]
        cur = GF(1)
        for _ in range(lp - 1):
            cur = cur * gen
            pts.append(int(cur))
        root_groups.append(pts)

    P = list(iproduct(*root_groups))  # all root tuples, as tuples of ints

    def frob(tup):
        # square each coordinate in GF(2^N), then drop back to int
        return tuple(int(GF(x) ** 2) for x in tup)

    seen = set()
    components = []
    for t in P:
        if t in seen:
            continue
        orbit = []
        cur = t
        while cur not in seen:
            seen.add(cur)
            orbit.append(cur)
            cur = frob(cur)
        Dc = len(orbit)
        rep = tuple(GF(x) for x in orbit[0])
        orbit_gf = tuple(tuple(GF(x) for x in tup) for tup in orbit)
        components.append(Component(index=len(components), rep=rep,
                                     orbit=orbit_gf, Dc=Dc, dim=Dc * (2 ** S)))
    return components


if __name__ == "__main__":
    # --- Validation 1: Example 1 of the draft, L=(3,4,6) ---
    # Expect S=3, five components with dims 8,16,16,16,16 (sum=72=3*4*6).
    rd = ring_setup((3, 4, 6))
    dims = sorted(c.dim for c in rd.components)
    print("L=(3,4,6):  s =", rd.s, " S =", rd.S, " N =", rd.N)
    print("  component dims:", dims, " sum =", sum(dims), " expect 72")
    assert rd.S == 3
    assert dims == [8, 16, 16, 16, 16]
    assert sum(dims) == 72
    print("  PASS\n")

    # --- Validation 2: L=(3,3) odd x odd example of §6.1.2 ---
    # Expect 5 components with dims 1,2,2,2,2 (sum=9).
    rd2 = ring_setup((3, 3))
    dims2 = sorted(c.dim for c in rd2.components)
    print("L=(3,3):  s =", rd2.s, " S =", rd2.S, " N =", rd2.N)
    print("  component dims:", dims2, " sum =", sum(dims2), " expect 9")
    assert rd2.S == 0
    assert dims2 == [1, 2, 2, 2, 2]
    print("  PASS\n")

    # --- Validation 3: L=(2,2) (toric-code-like), even x even, used in §5.10 ---
    # Expect a single component, S=2, e=2, dim = 1*2^2 = 4.
    rd3 = ring_setup((2, 2))
    print("L=(2,2):  s =", rd3.s, " e =", rd3.e, " S =", rd3.S)
    print("  num components:", len(rd3.components), "dim:", rd3.components[0].dim)
    assert rd3.e == 2 and rd3.S == 2 and len(rd3.components) == 1
    assert rd3.components[0].dim == 4
    print("  PASS")
