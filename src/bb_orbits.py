"""
Orbit decomposition of the joint-linear solution space (Prop. orbit-split).

Group used: <sigma_psi (psi in the symmetry set), '*'>  acting on components, where
'*' is the bar involution c -> c^* (needed because gZ involves f-bar, and bar(1_c)=1_{c^*}).
"""
from __future__ import annotations
import itertools, numpy as np, galois
from bb_ring_elt import RingElement, local_jet
from bb_crt import CRTBasis
from bb_theta_inverse import _mons, _vec, _elt, constraint_matrix

GF2 = galois.GF(2)

def _root_key(rd, tup): return tuple(int(x) for x in tup)

def _orbit_lookup(rd):
    look = {}
    for c in rd.components:
        for t in c.orbit: look[_root_key(rd, t)] = c.index
    return look

def component_perm(A, rd):
    """sigma_psi: (psi r)(alpha) = r(beta), beta_j = prod_i alpha_i^{A[i][j]}  (pullback identity)."""
    look = _orbit_lookup(rd); perm = {}
    for c in rd.components:
        a = c.rep; k = rd.k
        beta = []
        for j in range(k):
            v = rd.GF(1)
            for i in range(k): v = v * (a[i] ** (A[i][j] % (rd.GF.order - 1)))
            beta.append(v)
        perm[c.index] = look[_root_key(rd, beta)]
    return perm

def bar_perm(rd):
    look = _orbit_lookup(rd); perm = {}
    for c in rd.components:
        inv = [x ** (rd.GF.order - 2) for x in c.rep]
        perm[c.index] = look[_root_key(rd, inv)]
    return perm

def orbits_of(perms, rd):
    """orbits of the group generated by the given permutations of component indices."""
    n = len(rd.components); parent = list(range(n))
    def find(x):
        while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for p in perms:
        for a, b in p.items(): parent[find(a)] = find(b)
    groups = {}
    for i in range(n): groups.setdefault(find(i), []).append(i)
    return sorted(groups.values())

def split_solution_space(V, rd, crt: CRTBasis, orbit):
    """V: list of (f1,f2). Returns F2-basis (list of (f1,f2)) of e_O V."""
    L = rd.L; mons = _mons(L); n = len(mons)
    e = RingElement(L, [])
    for c in orbit: e = e + crt.idempotent(c)
    rows = [np.concatenate([_vec(e * f1, mons), _vec(e * f2, mons)]) for f1, f2 in V]
    if not rows: return []
    R = GF2(np.array(rows, dtype=np.uint8)).row_reduce()
    R = R[[i for i in range(R.shape[0]) if R[i].any()]]
    return [(_elt(L, r[:n], mons), _elt(L, r[n:], mons)) for r in R]
